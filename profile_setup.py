#!/usr/bin/env python3
import os
import re
from pathlib import Path
from getpass import getpass

BASE = Path.home() / "pdfunlocker"
PROFILE = BASE / "profile.env"

FIELDS = [
    ("FIRST_NAME", "First name"),
    ("MIDDLE_NAME", "Middle name"),
    ("LAST_NAME", "Last name"),
    ("FULL_NAME", "Full name"),
    ("BIRTH_DAY", "Birth day (DD)"),
    ("BIRTH_MONTH", "Birth month (MM)"),
    ("BIRTH_YEAR", "Birth year (YYYY)"),
    ("DOB_DDMM", "Date of birth (DDMM)"),
    ("DOB_DDMMYY", "Date of birth (DDMMYY)"),
    ("DOB_DDMMYYYY", "Date of birth (DDMMYYYY)"),
    ("EMAIL_01", "Email address 1"),
    ("EMAIL_02", "Email address 2"),
    ("PAN", "PAN (optional)"),
    ("PINCODE", "PIN code"),
    ("EMPLOYEE_ID_01", "Employee ID"),
    ("EMPLOYER_NAME", "Employer name"),
    ("EMPLOYER_TAN", "Employer TAN"),
    ("CARD_LAST4_01", "Card last 4 digits only"),
]

MULTIPLE_FIELDS = [
    ("MOBILE", "Mobile number"),
    ("ACCOUNT_NUMBER", "Account number"),
    ("CUSTOMER_ID", "Customer ID"),
    ("CIF_ID", "CIF ID"),
]

def ask(label):
    return input(f"{label}: ").strip()

def safe_value(value):
    return value.replace("\\", "\\\\").replace("\n", "").replace("\r", "")

def main():
    BASE.mkdir(parents=True, exist_ok=True)
    os.chmod(BASE, 0o700)

    print("\n================================")
    print("     PDFUnlocker Lite Setup")
    print("================================")
    print("Creates one local profile.env.")
    print("Leave optional fields blank.")
    print("You can add any number of repeated identifiers.\n")

    if PROFILE.exists():
        choice = input("profile.env already exists. [O]verwrite / [C]ancel? ").strip().lower()
        if choice != "o":
            print("Cancelled; existing profile was not changed.")
            return

    values = {}
    for key, label in FIELDS:
        values[key] = ask(label)

    for prefix, label in MULTIPLE_FIELDS:
        print(f"\n{label} — add as many as needed; press Enter when finished.")
        entries = []
        while True:
            value = ask(f"{label} #{len(entries) + 1}")
            if not value:
                break
            entries.append(value)
        values[prefix] = entries

    lines = [
        "# PDFUnlocker Lite profile",
        "# Generated by profile_setup.py. Keep this file private.",
        "",
    ]

    for key, value in values.items():
        if isinstance(value, list):
            lines.append(f"{key}_COUNT={len(value)}")
            for index, item in enumerate(value, 1):
                lines.append(f"{key}_{index:03d}={safe_value(item)}")
        else:
            lines.append(f"{key}={safe_value(value)}")

    temporary = PROFILE.with_suffix(".env.tmp")
    temporary.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(temporary, 0o600)
    temporary.replace(PROFILE)
    os.chmod(PROFILE, 0o600)

    print("\nProfile created successfully.")
    print(f"Location: {PROFILE}")
    print("Permissions: owner read/write only")
    print("Repeated fields are numbered, e.g. MOBILE_001, MOBILE_002, ...")
    print("This setup creates the profile only; PDF processing is not started.")

if __name__ == "__main__":
    main()
